import init from '@echogarden/espeak-ng-emscripten';
import {writeFile,mkdir} from 'node:fs/promises';
import {createHash} from 'node:crypto';
import {blueLines,newLines} from '../dist/dialogue.js';
import {exchanges,conclusions} from '../dist/conversation.js';

const texts=[...new Set([...blueLines,...newLines.blue,...exchanges.flat().filter(turn=>turn.voice===0).map(turn=>turn.text),...conclusions.filter(turn=>turn.voice===0).map(turn=>turn.text)])];
const module=await init(),voice=new module.eSpeakNGWorker(),rate=22050;
voice.set_voice('en-us');voice.set_rate(.88);voice.set_pitch(.72);voice.set_range(.65);
const directory=new URL('../dist/blue-speech/',import.meta.url);await mkdir(directory,{recursive:true});
const manifest={};
for(const text of texts){
  const chunks=[],events=[];
  voice.synthesize(text,(samples,markers)=>{if(samples?.length)chunks.push(Int16Array.from(samples));events.push(...markers)});
  const length=chunks.reduce((sum,chunk)=>sum+chunk.length,0),pcm=new Float32Array(length);
  let offset=0,peak=0;
  for(const chunk of chunks){for(const sample of chunk){pcm[offset++]=sample/32768;peak=Math.max(peak,Math.abs(sample/32768));}}
  if(!peak)throw new Error(`Empty speech: ${text}`);
  const fade=Math.round(rate*.008);
  for(let i=0;i<pcm.length;i++)pcm[i]*=.95/peak*Math.min(1,i/fade,(pcm.length-1-i)/fade);
  const activity=[],window=Math.round(rate*.03);
  for(let start=0;start<length;start+=window){
    const end=Math.min(length,start+window);let energy=0;
    for(let i=start;i<end;i++)energy+=pcm[i]*pcm[i];
    if(Math.sqrt(energy/(end-start))>.012){
      const previous=activity.at(-1);
      if(previous&&start/rate-previous[1]<.045)previous[1]=end/rate;else activity.push([start/rate,end/rate]);
    }
  }
  const words=events.filter(event=>event.type==='word').map(event=>{
    let end=event.text_position-1+event.word_length;
    while(end<text.length&&!/\s/.test(text[end]))end++;
    return {at:event.audio_position/1000,text:text.slice(0,end)};
  });
  if(!words.length)throw new Error(`Missing word timing: ${text}`);
  words.at(-1).text=text;
  const name=createHash('sha256').update(text).digest('hex').slice(0,12)+'.wav';
  const wav=Buffer.alloc(44+length*2);
  wav.write('RIFF');wav.writeUInt32LE(wav.length-8,4);wav.write('WAVEfmt ',8);wav.writeUInt32LE(16,16);
  wav.writeUInt16LE(1,20);wav.writeUInt16LE(1,22);wav.writeUInt32LE(rate,24);wav.writeUInt32LE(rate*2,28);
  wav.writeUInt16LE(2,32);wav.writeUInt16LE(16,34);wav.write('data',36);wav.writeUInt32LE(length*2,40);
  for(let i=0;i<length;i++)wav.writeInt16LE(Math.round(pcm[i]*32767),44+i*2);
  await writeFile(new URL(name,directory),wav);
  manifest[text]={file:'blue-speech/'+name,duration:length/rate,words,activity:activity.map(pair=>pair.map(time=>Math.round(time*1000)/1000))};
}
await writeFile(new URL('../dist/blue-speech-data.js',import.meta.url),'// Generated by npm run voices. eSpeak NG formant speech and word timing.\nexport const blueSpeechData = '+JSON.stringify(manifest)+';\n');
console.log(`Generated ${texts.length} blue speech clips.`);
