import init from '@echogarden/espeak-ng-emscripten';
import {writeFile,mkdir} from 'node:fs/promises';
import {createHash} from 'node:crypto';
import {lyrics,singingSyllables} from '../dist/conversation.js';
const module=await init(),voice=new module.eSpeakNGWorker(),rate=22050;
voice.set_voice('en-us');voice.set_rate(155);voice.set_pitch(45);voice.set_range(0);
const directory=new URL('../dist/blue-speech/',import.meta.url);await mkdir(directory,{recursive:true});
const words=[...new Set(Object.values(lyrics).flat().flatMap(line=>line.toLowerCase().split(' ')))],manifest={};
const vowelPattern=/[aeiouyᵻæɑɐɒɔəɚɛɜɝɞɪɨʉʊʌœøɶɤɯ]/;
function pitchMarks(pcm,start,end){
  const lo=Math.round(start*rate),hi=Math.min(pcm.length,Math.round(end*rate));
  const mid=Math.floor((lo+hi)/2),span=Math.min(Math.floor((hi-lo)/3),Math.round(rate*.025));
  if(span<80)return{};
  const scores=[];
  for(let lag=Math.floor(rate/230);lag<=Math.ceil(rate/40);lag++){
    let cross=0,a2=0,b2=0;
    for(let i=mid-span;i<mid+span&&i+lag<hi;i++){const a=pcm[i],b=pcm[i+lag];cross+=a*b;a2+=a*a;b2+=b*b;}
    scores.push({lag,score:cross/Math.sqrt(a2*b2+1e-15)});
  }
  const best=Math.max(...scores.map(p=>p.score));if(best<.55)return{};
  const peaks=scores.filter((p,i)=>i&&i<scores.length-1&&p.score>=scores[i-1].score&&p.score>=scores[i+1].score&&p.score>=best*.92);
  const period=(peaks[0]??scores.reduce((a,b)=>a.score>b.score?a:b)).lag;
  const peakAround=(center,radius)=>{
    let peak=Math.max(lo,Math.round(center-radius));
    for(let i=peak+1;i<Math.min(hi,center+radius);i++)if(pcm[i]>pcm[peak])peak=i;
    return peak;
  };
  const marks=[peakAround(lo+period/2,period/2)];
  while(marks.at(-1)+period<hi){const next=peakAround(marks.at(-1)+period,period*.22);if(next<=marks.at(-1))break;marks.push(next)}
  return{period,marks};
}
for(const word of words){
  const chunks=[],events=[];
  voice.synthesize_and_get_phonemes(word,(samples,markers)=>{if(samples?.length)chunks.push(Int16Array.from(samples));events.push(...markers)});
  const length=chunks.reduce((sum,c)=>sum+c.length,0),pcm=new Float32Array(length);let cursor=0,peak=0;
  for(const chunk of chunks)for(const sample of chunk){pcm[cursor++]=sample/32768;peak=Math.max(peak,Math.abs(sample/32768))}
  for(let i=0;i<length;i++)pcm[i]*=.95/peak*Math.min(1,i/(rate*.005),(length-1-i)/(rate*.005));
  const eventsPhonemes=events.filter(e=>e.type==='phoneme');
  const phonemes=eventsPhonemes.flatMap((event,index)=>{
    if(!event.id)return[];
    const start=event.audio_position/1000,end=(eventsPhonemes[index+1]?.audio_position??length/rate*1000)/1000;
    if(end<=start)return[];
    const vowel=vowelPattern.test(event.id);
    return[{ipa:event.id,start,end,vowel,...(vowel||/^[mnŋlɹrɾjw]+$/.test(event.id)?pitchMarks(pcm,start,end):{})}];
  });
  const count=singingSyllables(word).length;
  const vowels=phonemes.flatMap((p,i)=>p.vowel&&!(count===1&&i&&phonemes[i-1].vowel)?[i]:[]);
  if(vowels.length!==count)throw new Error(`${word}: ${vowels.length} vowel nuclei, expected ${count}`);
  const boundaries=[0,...vowels.slice(1).map((index,i)=>Math.max(vowels[i]+1,index-1)),phonemes.length];
  const syllables=boundaries.slice(0,-1).map((start,index)=>phonemes.slice(start,boundaries[index+1]));
  const name=createHash('sha256').update('sing:'+word).digest('hex').slice(0,12)+'.wav';
  const wav=Buffer.alloc(44+length*2);wav.write('RIFF');wav.writeUInt32LE(wav.length-8,4);wav.write('WAVEfmt ',8);wav.writeUInt32LE(16,16);wav.writeUInt16LE(1,20);wav.writeUInt16LE(1,22);wav.writeUInt32LE(rate,24);wav.writeUInt32LE(rate*2,28);wav.writeUInt16LE(2,32);wav.writeUInt16LE(16,34);wav.write('data',36);wav.writeUInt32LE(length*2,40);
  for(let i=0;i<length;i++)wav.writeInt16LE(Math.round(pcm[i]*32767),44+i*2);
  await writeFile(new URL(name,directory),wav);
  manifest[word]={file:'blue-speech/'+name,duration:length/rate,syllables};
}
await writeFile(new URL('../dist/blue-singing-data.js',import.meta.url),'// Generated by npm run singing. Pronunciation and pitch marks from eSpeak NG.\nexport const blueSingingData = '+JSON.stringify(manifest)+';\n');
console.log('Generated '+words.length+' sung word pronunciations.');
